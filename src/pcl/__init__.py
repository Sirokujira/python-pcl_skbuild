def _load(cls, path, format):
    fmt = _infer_format(path, format)
    if fmt in _XYZ_LOADERS:
        if cls is not PointCloud:
            raise ValueError("%s files hold x, y, z only: load them with "
                             "pcl.load" % fmt)
        cloud = PointCloud()
        reader = functools.partial(_XYZ_LOADERS[fmt], cloud)
    elif fmt in _LOADERS:
        cloud = cls()
        reader = getattr(cloud, _LOADERS[fmt])
    else:
        raise ValueError(
            "unsupported format %r (wrapped: %s)"
            % (fmt, ", ".join(sorted(set(_LOADERS) | set(_XYZ_LOADERS))))
        )

    if _is_gzipped(path, format):
        with _decompressed(path, fmt) as plain:
            error = reader(plain)
    else:
        error = reader(path)
    if error:
        raise IOError("error while loading %s (code %d)" % (path, error))
    return cloud


def save(cloud, path, format=None, binary=False):
    """Save a cloud of any wrapped point type to *path* (.pcd or .ply, or
    .ifs for a :class:`PointCloud`; ``format`` overrides the extension).

    A ``.gz`` suffix compresses, mirroring :func:`load`.
    """
    fmt = _infer_format(path, format)
    if fmt in _XYZ_SAVERS:
        if not isinstance(cloud, PointCloud):
            raise ValueError("%s files hold x, y, z only: save a PointCloud"
                             % fmt)
        writer = functools.partial(_XYZ_SAVERS[fmt], cloud)
    elif fmt in _SAVERS:
        writer = getattr(cloud, _SAVERS[fmt])
    else:
        raise ValueError(
            "unsupported format %r (wrapped: %s)"
            % (fmt, ", ".join(sorted(set(_SAVERS) | set(_XYZ_SAVERS))))
        )
    if _is_gzipped(path, format):
        error = _save_gzipped(writer, path, fmt, binary)
    else:
        error = writer(path, binary)
    if error:
        raise IOError("error while saving %s (code %d)" % (path, error))


def save_XYZRGBA(cloud, path, format=None, binary=False):
    """python-pcl spelling; `save` already handles every point type."""
    return save(cloud, path, format=format, binary=binary)


def _is_gzipped(path, format):
    return format is None and str(path).lower().endswith(".gz")


def _save_gzipped(writer, path, fmt, binary):
    """Write through a plain temporary file, then gzip it into place.

    The save-side counterpart of `_decompressed`, and needed for the same
    reason: PCL's writers take a filename and open it themselves, so they
    cannot compress. Without this, `save` left an UNCOMPRESSED cloud at a
    `.gz` path and `load` then refused to read it back.

    Compresses only on a successful write, so a failed save does not
    leave a truncated `.gz` behind.
    """
    handle, plain = tempfile.mkstemp(suffix="." + fmt)
    os.close(handle)
    try:
        error = writer(plain, binary)
        if not error:
            with open(plain, "rb") as src, gzip.open(path, "wb") as dst:
                shutil.copyfileobj(src, dst)
        return error
    finally:
        os.unlink(plain)


@contextlib.contextmanager
def _decompressed(path, fmt):
    """Yield a plain temporary copy of a gzipped cloud file."""
    handle, plain = tempfile.mkstemp(suffix="." + fmt)
    os.close(handle)
    try:
        with gzip.open(path, "rb") as src, open(plain, "wb") as dst:
            shutil.copyfileobj(src, dst)
        yield plain
    finally:
        os.unlink(plain)


def _infer_format(path, format):
    if format is not None:
        return format.lower()
    name = str(path)
    if name.lower().endswith(".gz"):
        name = name[: -len(".gz")]
    return os.path.splitext(name)[1][1:].lower()


def transform_cloud(cloud, matrix):
    """Return *cloud* moved by a 4x4 rigid transform.

    The free-function spelling of ``cloud.transform(matrix)``, for any
    wrapped point type. The matrix is what registration and recognition
    return, so a result applies directly:

        converged, matrix, _, _ = icp.icp(source, target)
        aligned = pcl.transform_cloud(source, matrix)
    """
    try:
        method = cloud.transform
    except AttributeError:
        raise TypeError(
            "transform_cloud() needs a point cloud, got %r"
            % type(cloud).__name__) from None
    return method(matrix)
