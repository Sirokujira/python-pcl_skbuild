_LOADERS = {"pcd": "_from_pcd_file", "ply": "_from_ply_file"}
_SAVERS = {"pcd": "_to_pcd_file", "ply": "_to_ply_file"}


def load(path, format=None):
    """Load a point cloud from *path* (.pcd or .ply; ``format`` overrides
    the extension). Returns a :class:`PointCloud`.

    A ``.gz`` suffix is decompressed transparently — PCL's readers take a
    filename and open it themselves, so a gzipped cloud is unreadable
    without this (strawlab/python-pcl#131).
    """
    fmt = _infer_format(path, format)
    if fmt not in _LOADERS:
        raise ValueError(
            "unsupported format %r (wrapped: %s)"
            % (fmt, ", ".join(sorted(_LOADERS)))
        )

    cloud = PointCloud()
    if _is_gzipped(path, format):
        with _decompressed(path, fmt) as plain:
            error = getattr(cloud, _LOADERS[fmt])(plain)
    else:
        error = getattr(cloud, _LOADERS[fmt])(path)
    if error:
        raise IOError("error while loading %s (code %d)" % (path, error))
    return cloud


def save(cloud, path, format=None, binary=False):
    """Save :class:`PointCloud` *cloud* to *path* (.pcd or .ply;
    ``format`` overrides the extension)."""
    fmt = _infer_format(path, format)
    if fmt not in _SAVERS:
        raise ValueError(
            "unsupported format %r (wrapped: %s)"
            % (fmt, ", ".join(sorted(_SAVERS)))
        )
    error = getattr(cloud, _SAVERS[fmt])(path, binary)
    if error:
        raise IOError("error while saving %s (code %d)" % (path, error))


def _is_gzipped(path, format):
    return format is None and str(path).lower().endswith(".gz")


@contextlib.contextmanager
def _decompressed(path, fmt):
    """Yield a plain temporary copy of a gzipped cloud file."""
    handle, plain = tempfile.mkstemp(suffix="." + fmt)
    os.close(handle)
    try:
        with gzip.open(path, "rb") as src, open(plain, "wb") as dst:
            shutil.copyfileobj(src, dst)
        yield plain
    finally:
        os.unlink(plain)


def _infer_format(path, format):
    if format is not None:
        return format.lower()
    name = str(path)
    if name.lower().endswith(".gz"):
        name = name[: -len(".gz")]
    return os.path.splitext(name)[1][1:].lower()
